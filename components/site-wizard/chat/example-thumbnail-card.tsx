"use client";

import React, { useMemo } from "react";
import { ChevronRight, X } from "lucide-react";
import { useI18n } from "@/lib/i18n/context";
import {
  useMockupShowcaseSites,
  useAllRealSitesData,
  siteHost,
  resolveSiteArchetype,
} from "@/lib/mockup-showcase-sites";
import { ARCHETYPE_GROUPS, archetypeGroup } from "@/lib/showcase-archetypes";

interface ExampleThumbnailCardProps {
  onSeeAll: () => void;
  onSelectTab?: (groupKey: string) => void;
  onDismiss?: () => void;
}

const GROUP_ASSETS: Record<string, { icon: string; thumbnail: string }> = {
  kuliner_toko: {
    icon: "/inspiration/icon_kuliner.png",
    thumbnail: "/inspiration/thumbnail_kuliner_resto.png",
  },
  jasa_reservasi: {
    icon: "/inspiration/icon_jasa_reservasi.png",
    thumbnail: "/inspiration/thumbnail_jasa_bookly.png",
  },
  kreatif_pro: {
    icon: "/inspiration/icon_kreatif_pro.png",
    thumbnail: "/inspiration/thumbnail_kreatif_studio.png",
  },
  bisnis_institusi: {
    icon: "/inspiration/icon_bisnis_institusi.png",
    thumbnail: "/inspiration/thumbnail_bizcorp.png",
  },
};

export function ExampleThumbnailCard({
  onSeeAll,
  onSelectTab,
  onDismiss,
}: ExampleThumbnailCardProps) {
  const { t, isIndonesian } = useI18n();
  // Curated by admin/superadmin: published sites only (GET /public/showcase-sites)
  const { sites: effectiveSites } = useMockupShowcaseSites();

  const realSitesData = useAllRealSitesData(effectiveSites);

  // Up to 4 thumbnails, strictly 1 representative site per unique parent group.
  // `index` is the position in the full list (what onSelectTab expects).
  const displaySites = useMemo(() => {
    const indexed = effectiveSites.map((site, index) => ({
      site,
      index,
      archetype: resolveSiteArchetype(site, realSitesData[siteHost(site.url)]),
    }));
    const picked: typeof indexed = [];
    const seen = new Set<string>();
    for (const it of indexed) {
      if (picked.length >= 4) break;
      const group = archetypeGroup(it.archetype);
      if (seen.has(group.key)) continue;
      seen.add(group.key);
      picked.push(it);
    }
    // Sort by canonical ARCHETYPE_GROUPS order so cards match modal tab order
    const groupOrder = new Map(ARCHETYPE_GROUPS.map((g, i) => [g.key, i]));
    picked.sort((a, b) => {
      const ia = groupOrder.get(archetypeGroup(a.archetype).key) ?? 99;
      const ib = groupOrder.get(archetypeGroup(b.archetype).key) ?? 99;
      return ia - ib;
    });
    return picked;
  }, [effectiveSites, realSitesData]);

  if (displaySites.length === 0) return null;

  return (
    <div
      className="relative rounded-2xl border border-white/15 p-3 space-y-2.5 backdrop-blur-xl shadow-[0_18px_50px_rgba(0,0,0,0.72)] ring-1 ring-white/[0.06]"
      style={{ background: "rgba(20, 23, 30, 0.94)" }}
    >
      {/* Header row */}
      <div className="flex items-start justify-between gap-2">
        <div className="flex items-center gap-2.5 min-w-0">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src="/inspiration/icon_grid_section.png"
            alt=""
            className="shrink-0 w-8 h-8 rounded-xl object-cover border border-white/[0.08]"
          />
          <div className="min-w-0">
            <p className="text-[13px] font-bold text-white leading-snug">
              {t("dashboard.wizard.exampleCardTitle", isIndonesian ? "Inspirasi Website" : "Website Inspiration")}
            </p>
            <p className="text-[11px] text-white/45 leading-tight truncate">
              {t("dashboard.wizard.exampleCardSubtitle", isIndonesian
                ? "Contoh website nyata hasil generate AI"
                : "Real websites generated by AI")}
            </p>
          </div>
        </div>
        <div className="shrink-0 flex items-center gap-1.5">
          <button
            type="button"
            onClick={onSeeAll}
            className="flex items-center gap-1 rounded-full border border-white/15 bg-white/[0.05] hover:bg-white/12 px-2.5 py-1 text-[11px] font-semibold text-white/80 hover:text-white transition-colors whitespace-nowrap cursor-pointer"
          >
            {t("dashboard.wizard.exampleCardSeeAll", isIndonesian ? "Lihat semua" : "See all")}
            <ChevronRight className="w-3 h-3" />
          </button>
          {onDismiss && (
            <button
              type="button"
              onClick={onDismiss}
              aria-label={isIndonesian ? "Tutup" : "Close"}
              title={isIndonesian ? "Tutup" : "Close"}
              className="w-6 h-6 rounded-lg bg-white/[0.06] hover:bg-white/15 border border-white/10 text-white/60 hover:text-white flex items-center justify-center transition-all active:scale-90 cursor-pointer"
            >
              <X className="w-3.5 h-3.5 stroke-[2.2]" />
            </button>
          )}
        </div>
      </div>

      {/* Portrait 1-row grid fitted cleanly inside the chat panel */}
      <div
        className="grid gap-1.5"
        style={{
          gridTemplateColumns: `repeat(${displaySites.length}, minmax(0, 1fr))`,
        }}
      >
        {displaySites.map(({ site, index: idx, archetype }) => {
          const group = archetypeGroup(archetype);
          const groupLabel = isIndonesian ? group.shortId : group.shortEn;
          const asset = GROUP_ASSETS[group.key] ?? GROUP_ASSETS.bisnis_institusi;

          return (
            <button
              key={site.url || idx}
              type="button"
              onClick={() => (onSelectTab ? onSelectTab(group.key) : onSeeAll())}
              className="group flex flex-col gap-1.5 rounded-2xl bg-[#181a20] hover:bg-[#1e2129] border border-white/[0.08] hover:border-white/25 p-1 text-left transition-all duration-200 hover:-translate-y-0.5 active:scale-[0.98] focus:outline-none cursor-pointer"
            >
              {/* Top group bar: icon + group label + compact arrow */}
              <div className="flex items-center gap-1 px-0.5 pt-0.5 min-h-[22px]">
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img
                  src={asset.icon}
                  alt=""
                  className="w-4 h-4 rounded-full object-cover shrink-0 border border-white/[0.06]"
                />
                <span className="flex-1 min-w-0 text-[8.5px] font-semibold text-white/95 leading-[1.15] tracking-tight line-clamp-2">
                  {groupLabel}
                </span>
              </div>

              {/* Portrait thumbnail artwork */}
              <div className="relative w-full aspect-[4/5] rounded-xl overflow-hidden bg-[#eceef2]">
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img
                  src={asset.thumbnail}
                  alt={groupLabel}
                  className="w-full h-full object-cover transition-transform duration-300 group-hover:scale-[1.03]"
                  loading="lazy"
                />
              </div>
            </button>
          );
        })}
      </div>
    </div>
  );
}
