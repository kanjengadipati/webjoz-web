"use client";

import React, { useMemo } from "react";
import { ArrowRight, ChevronRight, Menu, X } from "lucide-react";
import { useI18n } from "@/lib/i18n/context";
import {
  useMockupShowcaseSites,
  useAllRealSitesData,
  siteHost,
  resolveSiteBusinessName,
  resolveSiteArchetype,
} from "@/lib/mockup-showcase-sites";
import { archetypeGroup } from "@/lib/showcase-archetypes";
import { ArchetypeThumbnailArt } from "@/components/archetype-thumbnail-art";
import { ArchetypeIcon } from "@/components/archetype-icon";

interface ExampleThumbnailCardProps {
  onSeeAll: () => void;
  onSelectTab?: (showcaseIndex: number) => void;
  onDismiss?: () => void;
}

const GROUP_HERO_COPY: Record<
  string,
  {
    headlineId: string;
    headlineEn: string;
    subId: string;
    subEn: string;
    ctaId: string;
    ctaEn: string;
  }
> = {
  kuliner_toko: {
    headlineId: "Sajian & Produk Terbaik.",
    headlineEn: "Good Food. Great Goods.",
    subId: "Kualitas pilihan, siap pesan.",
    subEn: "Curated quality, made with care.",
    ctaId: "Pesan",
    ctaEn: "Order Now",
  },
  jasa_reservasi: {
    headlineId: "Booking Lebih Mudah.",
    headlineEn: "Book Your Service Easily",
    subId: "Cepat, praktis, terpercaya.",
    subEn: "Fast. Simple. Reliable.",
    ctaId: "Reservasi",
    ctaEn: "Reserve Now",
  },
  kreatif_pro: {
    headlineId: "Wujudkan Ide Jadi Nyata.",
    headlineEn: "Turn Ideas Into Reality",
    subId: "Desain, karya, dan solusi.",
    subEn: "Design. Create. Inspire.",
    ctaId: "Mulai",
    ctaEn: "Get Started",
  },
  bisnis_institusi: {
    headlineId: "Bangun Bisnis Lebih Kuat.",
    headlineEn: "Build a Stronger Business",
    subId: "Solusi inovatif masa depan.",
    subEn: "Innovative solutions ahead.",
    ctaId: "Selengkapnya",
    ctaEn: "Learn More",
  },
};

export function ExampleThumbnailCard({
  onSeeAll,
  onSelectTab,
  onDismiss,
}: ExampleThumbnailCardProps) {
  const { t, isIndonesian } = useI18n();
  // Curated by admin/superadmin: published sites only (GET /public/showcase-sites)
  const { sites: effectiveSites } = useMockupShowcaseSites();

  const realSitesData = useAllRealSitesData(effectiveSites);

  // Up to 4 thumbnails, strictly 1 representative site per unique parent group.
  // `index` is the position in the full list (what onSelectTab expects).
  const displaySites = useMemo(() => {
    const indexed = effectiveSites.map((site, index) => ({
      site,
      index,
      archetype: resolveSiteArchetype(site, realSitesData[siteHost(site.url)]),
    }));
    const picked: typeof indexed = [];
    const seen = new Set<string>();
    for (const it of indexed) {
      if (picked.length >= 4) break;
      const group = archetypeGroup(it.archetype);
      if (seen.has(group.key)) continue;
      seen.add(group.key);
      picked.push(it);
    }
    return picked;
  }, [effectiveSites, realSitesData]);

  if (displaySites.length === 0) return null;

  return (
    <div
      className="relative rounded-2xl border border-white/15 p-3.5 space-y-3 backdrop-blur-xl shadow-[0_18px_50px_rgba(0,0,0,0.72)] ring-1 ring-white/[0.06]"
      style={{ background: "rgba(20, 23, 30, 0.94)" }}
    >
      {/* Header row */}
      <div className="flex items-start justify-between gap-2">
        <div className="flex items-center gap-2.5 min-w-0">
          {/* Icon box */}
          <div
            className="shrink-0 w-8 h-8 rounded-xl flex items-center justify-center border border-white/[0.08]"
            style={{ background: "rgba(255,255,255,0.07)" }}
          >
            <svg width="15" height="15" viewBox="0 0 15 15" fill="none" className="text-white/75">
              <rect x="1" y="1" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.9" />
              <rect x="8.5" y="1" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.5" />
              <rect x="1" y="8.5" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.5" />
              <rect x="8.5" y="8.5" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.25" />
            </svg>
          </div>
          <div className="min-w-0">
            <p className="text-[13px] font-bold text-white leading-snug">
              {t("dashboard.wizard.exampleCardTitle", isIndonesian ? "Inspirasi Website" : "Website Inspiration")}
            </p>
            <p className="text-[11px] text-white/45 leading-tight truncate">
              {t("dashboard.wizard.exampleCardSubtitle", isIndonesian
                ? "Contoh website nyata hasil generate AI"
                : "Real websites generated by AI")}
            </p>
          </div>
        </div>
        <div className="shrink-0 flex items-center gap-1.5">
          <button
            type="button"
            onClick={onSeeAll}
            className="flex items-center gap-1 rounded-full border border-white/15 bg-white/[0.05] hover:bg-white/12 px-2.5 py-1 text-[11px] font-semibold text-white/80 hover:text-white transition-colors whitespace-nowrap cursor-pointer"
          >
            {t("dashboard.wizard.exampleCardSeeAll", isIndonesian ? "Lihat semua" : "See all")}
            <ChevronRight className="w-3 h-3" />
          </button>
          {onDismiss && (
            <button
              type="button"
              onClick={onDismiss}
              aria-label={isIndonesian ? "Tutup" : "Close"}
              title={isIndonesian ? "Tutup" : "Close"}
              className="w-6 h-6 rounded-lg bg-white/[0.06] hover:bg-white/15 border border-white/10 text-white/60 hover:text-white flex items-center justify-center transition-all active:scale-90 cursor-pointer"
            >
              <X className="w-3.5 h-3.5 stroke-[2.2]" />
            </button>
          )}
        </div>
      </div>

      {/* 4-group horizontal card strip — keeps each card wide enough for crisp typography */}
      <div className="flex gap-2 overflow-x-auto no-scrollbar snap-x snap-mandatory pb-0.5">
        {displaySites.map(({ site, index: idx, archetype }) => {
          const host = siteHost(site.url);
          const data = realSitesData[host];
          const bName = resolveSiteBusinessName(site, data);
          const group = archetypeGroup(archetype);
          const groupLabel = isIndonesian ? group.labelId : group.labelEn;
          const copy = GROUP_HERO_COPY[group.key] ?? GROUP_HERO_COPY.bisnis_institusi;

          return (
            <button
              key={site.url || idx}
              type="button"
              onClick={() => (onSelectTab ? onSelectTab(idx) : onSeeAll())}
              className="group shrink-0 w-[166px] snap-start flex flex-col gap-2 rounded-2xl bg-[#181a20] hover:bg-[#1e2129] border border-white/[0.08] hover:border-white/25 p-2 text-left transition-all duration-200 hover:-translate-y-0.5 active:scale-[0.98] focus:outline-none cursor-pointer"
            >
              {/* Top group bar: icon + group label + arrow */}
              <div className="flex items-center gap-1.5 px-0.5 pt-0.5 min-h-[26px]">
                <div className="w-6 h-6 rounded-full bg-white/[0.08] border border-white/[0.06] flex items-center justify-center shrink-0">
                  <ArchetypeIcon id={group.archetypes[0]} className="w-3 h-3 text-white/90" />
                </div>
                <span className="flex-1 min-w-0 text-[10px] font-semibold text-white/90 leading-[1.2] line-clamp-2">
                  {groupLabel}
                </span>
                <div className="w-5 h-5 rounded-full bg-white/[0.07] group-hover:bg-white/20 flex items-center justify-center shrink-0 transition-colors">
                  <ArrowRight className="w-2.5 h-2.5 text-white/75 group-hover:text-white transition-transform group-hover:translate-x-0.5" />
                </div>
              </div>

              {/* Inner monochrome mini-website preview card */}
              <div className="relative h-[106px] w-full rounded-xl overflow-hidden bg-gradient-to-br from-[#f6f7f9] to-[#e6e9ef] text-[#111318] p-2.5 flex flex-col justify-between shadow-inner">
                {/* Monochrome editorial SVG decoration */}
                <ArchetypeThumbnailArt
                  id={group.key}
                  className="absolute inset-0 w-full h-full pointer-events-none transition-transform duration-300 group-hover:scale-105"
                />

                {/* Soft left readability wash so hero text always pops */}
                <div
                  className="absolute inset-0 pointer-events-none"
                  style={{
                    background:
                      "linear-gradient(105deg, rgba(246,247,249,0.94) 0%, rgba(246,247,249,0.78) 58%, rgba(246,247,249,0.08) 100%)",
                  }}
                />

                {/* Mini navbar */}
                <div className="relative z-10 flex items-center justify-between gap-1.5">
                  <div className="flex items-center gap-1 min-w-0">
                    <ArchetypeIcon id={group.archetypes[0]} className="w-2.5 h-2.5 shrink-0 text-[#111318]/80" />
                    <span className="text-[7.5px] font-bold text-[#111318]/90 truncate">
                      {bName}
                    </span>
                  </div>
                  <Menu className="w-2.5 h-2.5 shrink-0 text-[#111318]/65" />
                </div>

                {/* Mini hero copy + pill CTA */}
                <div className="relative z-10 max-w-[82%]">
                  <p className="text-[10.5px] font-extrabold leading-[1.12] tracking-tight text-[#0d0f14] line-clamp-2">
                    {isIndonesian ? copy.headlineId : copy.headlineEn}
                  </p>
                  <p className="text-[6.5px] text-[#4b515e] leading-tight truncate mt-0.5">
                    {isIndonesian ? copy.subId : copy.subEn}
                  </p>
                  <span className="mt-1.5 inline-flex items-center gap-1 whitespace-nowrap rounded-full bg-[#111318] text-white text-[6.5px] font-semibold px-2.5 py-0.5 w-fit">
                    <span>{isIndonesian ? copy.ctaId : copy.ctaEn}</span>
                    <ArrowRight className="w-2 h-2 shrink-0" />
                  </span>
                </div>
              </div>
            </button>
          );
        })}
      </div>
    </div>
  );
}
