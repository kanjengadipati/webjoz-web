"use client";

import React, { useMemo } from "react";
import { ChevronRight, X } from "lucide-react";
import { useI18n } from "@/lib/i18n/context";
import {
  useMockupShowcaseSites,
  useAllRealSitesData,
  siteHost,
  resolveSiteBusinessName,
  resolveSiteArchetype,
} from "@/lib/mockup-showcase-sites";
import { archetypeLabel } from "@/lib/showcase-archetypes";
import { ArchetypeThumbnailArt } from "@/components/archetype-thumbnail-art";
import { ArchetypeIcon } from "@/components/archetype-icon";

interface ExampleThumbnailCardProps {
  onSeeAll: () => void;
  onSelectTab?: (showcaseIndex: number) => void;
  onDismiss?: () => void;
}

export function ExampleThumbnailCard({
  onSeeAll,
  onSelectTab,
  onDismiss,
}: ExampleThumbnailCardProps) {
  const { t, isIndonesian } = useI18n();
  // Curated by admin/superadmin: published sites only (GET /public/showcase-sites)
  const { sites: effectiveSites } = useMockupShowcaseSites();

  const realSitesData = useAllRealSitesData(effectiveSites);

  // Up to 4 thumbnails, strictly 1 representative site per unique archetype (grouped by category).
  // `index` is the position in the full list (what onSelectTab expects).
  const displaySites = useMemo(() => {
    const indexed = effectiveSites.map((site, index) => ({
      site,
      index,
      archetype: resolveSiteArchetype(site, realSitesData[siteHost(site.url)]),
    }));
    const picked: typeof indexed = [];
    const seen = new Set<string>();
    for (const it of indexed) {
      if (picked.length >= 4) break;
      if (seen.has(it.archetype)) continue;
      seen.add(it.archetype);
      picked.push(it);
    }
    return picked;
  }, [effectiveSites, realSitesData]);

  if (displaySites.length === 0) return null;

  return (
    <div
      className="relative rounded-2xl border border-white/15 p-3.5 space-y-2.5 backdrop-blur-xl shadow-[0_18px_50px_rgba(0,0,0,0.72)] ring-1 ring-white/[0.06]"
      style={{ background: "rgba(20, 23, 30, 0.94)" }}
    >
      {/* Header row */}
      <div className="flex items-start justify-between gap-2">
        <div className="flex items-center gap-2 min-w-0">
          {/* Icon box */}
          <div
            className="shrink-0 w-8 h-8 rounded-xl flex items-center justify-center border border-white/[0.08]"
            style={{ background: "rgba(255,255,255,0.07)" }}
          >
            <svg width="15" height="15" viewBox="0 0 15 15" fill="none" className="text-white/75">
              <rect x="1" y="1" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.9" />
              <rect x="8.5" y="1" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.5" />
              <rect x="1" y="8.5" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.5" />
              <rect x="8.5" y="8.5" width="5.5" height="5.5" rx="1.2" fill="currentColor" opacity="0.25" />
            </svg>
          </div>
          <div className="min-w-0">
            <p className="text-[13px] font-bold text-white leading-snug">
              {t("dashboard.wizard.exampleCardTitle", isIndonesian ? "Inspirasi Website" : "Website Inspiration")}
            </p>
            <p className="text-[11px] text-white/45 leading-tight truncate">
              {t("dashboard.wizard.exampleCardSubtitle", isIndonesian
                ? "Contoh website nyata hasil generate AI"
                : "Real websites generated by AI")}
            </p>
          </div>
        </div>
        <div className="shrink-0 flex items-center gap-1.5">
          <button
            type="button"
            onClick={onSeeAll}
            className="flex items-center gap-0.5 text-[11px] font-semibold text-white/55 hover:text-white/85 transition-colors whitespace-nowrap cursor-pointer"
          >
            {t("dashboard.wizard.exampleCardSeeAll", isIndonesian ? "Lihat semua" : "See all")}
            <ChevronRight className="w-3 h-3" />
          </button>
          {onDismiss && (
            <button
              type="button"
              onClick={onDismiss}
              aria-label={isIndonesian ? "Tutup" : "Close"}
              title={isIndonesian ? "Tutup" : "Close"}
              className="w-6 h-6 rounded-lg bg-white/[0.06] hover:bg-white/15 border border-white/10 text-white/60 hover:text-white flex items-center justify-center transition-all active:scale-90 cursor-pointer"
            >
              <X className="w-3.5 h-3.5 stroke-[2.2]" />
            </button>
          )}
        </div>
      </div>

      {/* Thumbnail grid — dynamically reflects the real sites */}
      <div
        className="grid gap-1.5"
        style={{
          gridTemplateColumns: `repeat(${Math.max(2, Math.min(4, displaySites.length))}, minmax(0, 1fr))`,
        }}
      >
        {displaySites.map(({ site, index: idx, archetype }) => {
          const host = siteHost(site.url);
          const data = realSitesData[host];
          const bName = resolveSiteBusinessName(site, data);
          const categoryLabel = archetypeLabel(archetype, isIndonesian);

          return (
            <button
              key={site.url || idx}
              type="button"
              onClick={() => (onSelectTab ? onSelectTab(idx) : onSeeAll())}
              className="group flex flex-col rounded-xl overflow-hidden border border-white/[0.08] hover:border-white/20 transition-all duration-200 hover:scale-[1.03] active:scale-[0.97] focus:outline-none cursor-pointer"
            >
              {/* SVG Artwork + headline */}
              <div className="relative overflow-hidden" style={{ height: 100 }}>
                <ArchetypeThumbnailArt
                  id={archetype}
                  className="w-full h-full transition-transform duration-300 group-hover:scale-105"
                />
                {/* Dark scrim */}
                <div
                  className="absolute inset-0"
                  style={{
                    background:
                      "linear-gradient(to top, rgba(0,0,0,0.85) 0%, rgba(0,0,0,0.3) 50%, rgba(0,0,0,0.15) 100%)",
                  }}
                />

                {/* Subdomain pill at top-left */}
                <div
                  className="absolute top-1.5 left-1.5 font-mono truncate max-w-[85%]"
                  style={{
                    fontSize: "6px",
                    letterSpacing: "0.05em",
                    color: "rgba(255,255,255,0.75)",
                    lineHeight: 1,
                  }}
                >
                  {host}
                </div>

                {/* Business name — bottom */}
                <div
                  className="absolute bottom-1.5 left-1.5 right-1.5 leading-snug truncate"
                  style={{
                    fontSize: "12px",
                    fontWeight: 800,
                    color: "#ffffff",
                    letterSpacing: "-0.01em",
                    textShadow: "0 2px 8px rgba(0,0,0,0.7)",
                  }}
                >
                  {bName}
                </div>
              </div>

              {/* Label row */}
              <div
                className="flex items-center gap-1.5 px-2 py-1.5"
                style={{
                  background: "rgba(255,255,255,0.055)",
                  borderTop: "1px solid rgba(255,255,255,0.07)",
                }}
              >
                <ArchetypeIcon id={archetype} className="w-3 h-3 shrink-0 text-white/65" />
                <span className="text-[9.5px] font-semibold text-white/75 truncate leading-tight">
                  {categoryLabel}
                </span>
              </div>
            </button>
          );
        })}
      </div>
    </div>
  );
}
